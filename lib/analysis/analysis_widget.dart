/// Financial Analysis (Charts and Trends)
/// (i) Visual Charts
/// 1.
///
/// Monthly / Annual Income and Expenditure Trend Line Chart: Taking time as
/// the horizontal axis and the income and expenditure amount as the vertical
/// axis, it displays the trend of income and expenditure changes in different
/// periods of time, and supports the user to select different time ranges
/// (monthly, quarterly, annual) to view, and the mouse hovering over the line
/// can display the specific date and amount. At the same time, it provides a
/// comparison curve with the average level of the same industry or the same
/// age group to help users understand where their financial situation is in
/// the group.
/// 2. Categorized Expenditure Proportion Pie Chart: Visualize the proportion
/// of each categorized expenditure in the total expenditure, each sector is
/// labeled with the name of the categorization and the proportion of the
/// value, and clicking on the sector expands the detailed expenditure records
/// under the categorization. In addition, the pie chart comparison function
/// is provided for different time periods, which is convenient for users to
/// analyze the changes in the expenditure structure.
/// 3. Savings Rate Trend Chart: It presents the changes of users' savings
/// rate over time, analyzes the reasons for the growth or decline of savings
/// in combination with income and expenditure data, and helps users to
/// formulate a reasonable savings plan. At the same time, it provides a
/// savings target progress curve to compare with the actual savings rate and
/// visualize the target completion.
/// (ii) Detailed data display
/// 1. Detailed expenditure details under a certain category: Users can click
/// on a specific category (e.g. catering) to view the specific information of
/// each expenditure under the category, including time, amount, payment
/// method, notes, etc., and support sorting by chronological order and amount
/// size. In addition, it provides filtering and searching functions so that
/// users can quickly find specific expenditure records according to keywords.
/// 2. Expenditure Alert: When a certain type of expenditure exceeds the
/// preset budget or an abnormally large amount of expenditure occurs, it will
/// be prompted by eye-catching colors and icons in the data display area of
/// the category, and provide analysis of the reasons for the overspending and
/// suggestions for saving. At the same time, the warning information will be
/// synchronized to the home page and the notification center, which is
/// convenient for users to handle in time.
